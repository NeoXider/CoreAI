#!/usr/bin/env python3
"""Generate the shipped copies of the built-in agent skills from their single source.

A skill is authored once, as section files in ``skill-sources/<Skill>/``:

* ``skill.json`` names the skill, holds its one-line catalog description and says where the two shipped
  copies go: the Unity ``Resources`` text and the built-in C# constant (the fallback a host without
  Resources uses).
* ``NN-name.md`` files are the sections, in file-name order. The first is the entry document that a bare
  ``read_skill(name)`` returns; the others are read one at a time with ``read_skill(name, section)``.
  ``name`` is the section name the model asks for; the file's first line (``# ...``) is the one-line
  summary that the entry document lists for it. The entry must hold one ``<!-- sections -->`` line,
  replaced by that list.

Both copies get the same text: every section opened by a ``<!-- section: name -->`` line, which
``SkillSet.FromTextContent`` splits back into addressable sections. A skill with one file is written as
that file alone, without markers.

The output is deterministic (sorted files, LF, UTF-8 without BOM, a fixed C# template) and idempotent (a
second run changes nothing). ``SkillSourceCopiesEditModeTests`` fails when a copy and its source
disagree, and ``--check`` does the same from the command line.

Usage:
    python tools/generate_skills.py           # rewrite every copy that differs from its source
    python tools/generate_skills.py --check   # list copies that differ from their source; exit 1 if any
    python tools/generate_skills.py --sizes   # print each section's size
"""
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = os.path.join(REPO, "skill-sources")

SECTION_FILE = re.compile(r"^(\d{2})-([a-z0-9][a-z0-9-]*)\.md$")
MARKER = "<!-- section: {} -->"
MARKER_LINE = re.compile(r"^<!-- section: .* -->$", re.MULTILINE)
PLACEHOLDER = "<!-- sections -->"
REQUIRED_KEYS = ("name", "description", "resources", "csharp", "csharpClass")

CSHARP_TEMPLATE = """namespace CoreAI.Ai
{{
    /// <summary>
    /// Built-in "{name}" skill, read on demand through <c>read_skill</c>. Generated by
    /// <c>tools/generate_skills.py</c> from <c>skill-sources/{folder}</c>, which also writes the
    /// <c>{resources_name}</c> text: edit the section files there and run the script, never this file.
    /// <c>SkillSourceCopiesEditModeTests</c> fails when this copy and its source disagree.
    /// </summary>
    public static class {cls}
    {{
        /// <summary>Catalog name (what the model passes to <c>read_skill</c>).</summary>
        public const string SkillName = "{name_literal}";

        /// <summary>One-line catalog description shown before the model decides to read the skill.</summary>
        public const string SkillDescription =
            "{description_literal}";

        /// <summary>
        /// The skill text{sections_note}
        /// </summary>
        public const string Instructions = @"{instructions_literal}";
    }}
}}
"""

SECTIONED_NOTE = (": one document per section, each opened by a <c>&lt;!-- section: name --&gt;</c> line.\n"
                  "        /// <see cref=\"SkillSet.FromTextContent\"/> keeps the sections addressable, so a bare\n"
                  "        /// <c>read_skill</c> returns the entry document and its section list.")
SINGLE_NOTE = " returned by <c>read_skill</c>."


class SkillSourceError(Exception):
    pass


def read_text(path):
    with open(path, "rb") as handle:
        raw = handle.read()
    if raw.startswith(b"\xef\xbb\xbf"):
        raise SkillSourceError(f"{rel(path)}: remove the UTF-8 byte order mark")
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as error:
        raise SkillSourceError(f"{rel(path)}: not UTF-8 ({error})")
    return text.replace("\r\n", "\n")


def rel(path):
    return os.path.relpath(path, REPO).replace(os.sep, "/")


def csharp_string(text):
    if any(ch in text for ch in "\n\r\t"):
        raise SkillSourceError("a C# regular string literal may not contain control characters")
    return text.replace("\\", "\\\\").replace("\"", "\\\"")


def load_skill(folder):
    """Reads one skill folder into (manifest, [(section_name, title, content)]) and validates it."""
    manifest_path = os.path.join(folder, "skill.json")
    manifest = json.loads(read_text(manifest_path))
    for key in REQUIRED_KEYS:
        if not isinstance(manifest.get(key), str) or not manifest[key].strip():
            raise SkillSourceError(f"{rel(manifest_path)}: '{key}' must be a non-empty string")

    sections = []
    seen = set()
    for file_name in sorted(os.listdir(folder)):
        if file_name == "skill.json":
            continue
        match = SECTION_FILE.match(file_name)
        if not match:
            raise SkillSourceError(f"{rel(os.path.join(folder, file_name))}: section files are named NN-name.md")
        name = match.group(2)
        if name in seen:
            raise SkillSourceError(f"{rel(folder)}: two files define section '{name}'")
        seen.add(name)
        path = os.path.join(folder, file_name)
        content = read_text(path).rstrip("\n")
        first_line = content.split("\n", 1)[0]
        if not first_line.startswith("# ") or not first_line[2:].strip():
            raise SkillSourceError(f"{rel(path)}: the first line must be '# <one-line summary>'")
        if MARKER_LINE.search(content):
            raise SkillSourceError(f"{rel(path)}: a section may not contain a '<!-- section: ... -->' line")
        sections.append((name, first_line[2:].strip(), content))

    if not sections:
        raise SkillSourceError(f"{rel(folder)}: no section files")
    for index, (name, _, content) in enumerate(sections):
        placeholders = content.split("\n").count(PLACEHOLDER)
        expected = 1 if index == 0 and len(sections) > 1 else 0
        if placeholders != expected:
            where = "the entry section" if index == 0 else f"section '{name}'"
            raise SkillSourceError(
                f"{rel(folder)}: {where} must hold {expected} '{PLACEHOLDER}' line(s), found {placeholders}")
    return manifest, sections


def section_list(skill_name, sections):
    lines = [f"Sections (read_skill('{skill_name}', section='<name>')):"]
    for name, title, _ in sections[1:]:
        lines.append(f"- {name}: {title}")
    return "\n".join(lines)


def compose(manifest, sections):
    """The shipped skill text: what both the Resources copy and the C# constant hold."""
    if len(sections) == 1:
        return sections[0][2] + "\n"
    blocks = []
    for index, (name, _, content) in enumerate(sections):
        if index == 0:
            content = content.replace(PLACEHOLDER, section_list(manifest["name"], sections))
        blocks.append(MARKER.format(name) + "\n" + content + "\n")
    return "\n".join(blocks)


def csharp_file(manifest, folder, text, sectioned):
    return CSHARP_TEMPLATE.format(
        name=manifest["name"],
        folder=os.path.basename(folder),
        resources_name=manifest["resources"].split("/Resources/", 1)[-1].rsplit(".", 1)[0],
        cls=manifest["csharpClass"],
        name_literal=csharp_string(manifest["name"]),
        description_literal=csharp_string(manifest["description"]),
        sections_note=SECTIONED_NOTE if sectioned else SINGLE_NOTE,
        instructions_literal=text.replace("\"", "\"\""))


def outputs():
    """Every generated file as (repository path, expected text), for every skill source folder."""
    if not os.path.isdir(SOURCES):
        raise SkillSourceError(f"{rel(SOURCES)} does not exist")
    result = []
    for entry in sorted(os.listdir(SOURCES)):
        folder = os.path.join(SOURCES, entry)
        if not os.path.isdir(folder):
            continue
        manifest, sections = load_skill(folder)
        text = compose(manifest, sections)
        result.append((manifest["resources"], text))
        result.append((manifest["csharp"], csharp_file(manifest, folder, text, len(sections) > 1)))
    return result


def current(path):
    full = os.path.join(REPO, path)
    if not os.path.exists(full):
        return None
    with open(full, "rb") as handle:
        return handle.read().decode("utf-8")


def write(path, text):
    with open(os.path.join(REPO, path), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def print_sizes():
    for entry in sorted(os.listdir(SOURCES)):
        folder = os.path.join(SOURCES, entry)
        if not os.path.isdir(folder):
            continue
        manifest, sections = load_skill(folder)
        print(f"{manifest['name']}: {len(compose(manifest, sections))} characters in total")
        for index, (name, _, content) in enumerate(sections):
            if index == 0 and len(sections) > 1:
                content = content.replace(PLACEHOLDER, section_list(manifest["name"], sections))
            print(f"  {name:<14} {len(content):>6}")


def main(argv):
    mode = argv[1] if len(argv) > 1 else ""
    if mode not in ("", "--check", "--sizes"):
        print(__doc__)
        return 2
    try:
        if mode == "--sizes":
            print_sizes()
            return 0
        expected = outputs()
    except (SkillSourceError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    stale = [(path, text) for path, text in expected if current(path) != text]
    if mode == "--check":
        for path, _ in stale:
            print(f"out of date: {path} (run python tools/generate_skills.py)")
        return 1 if stale else 0
    for path, text in stale:
        write(path, text)
        print(f"wrote {path}")
    if not stale:
        print("all generated skill copies are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
